/**
 * Что видит человек. Ничего не знает про экраны — только про роли,
 * поэтому проверяется без базы и без браузера.
 *
 * Никого не вошло — показываем только витрину: незарегистрированный человек
 * пришёл смотреть каталог, это основной путь (§1). Остальные разделы клиента
 * ему показывать нельзя — за каждым стоит его компания, которой у него ещё нет,
 * и пункт меню, который всегда отвечает «сначала войдите», это тупик, а не
 * приглашение.
 *
 * Администратор видит И разделы оператора: на пилоте владелец площадки сам
 * же разбирает очередь, и отобрать у него рабочие экраны значило бы оставить
 * его с одним журналом. Разные интерфейсы, о которых говорит план спринта, —
 * это про то, что экраны не сливаются в один, а не про то, что администратор
 * лишён операторских.
 */
export function sectionsFor(org: Org | null, user: User | null): Section[] {
  return plannedFor(org, user).filter((section) => section.ready)
}

/**
 * Все разделы роли, включая те, чьих экранов ещё нет. Нужен плану и тестам:
 * по нему видно, куда система растёт, и он же следит, чтобы название раздела
 * не съехало в системный термин раньше, чем экран появится.
 */
export function plannedFor(org: Org | null, user: User | null): Section[] {
  if (!org || !user) return client.filter((section) => section.href === '/')

  if (org.isPlatform) {
    return user.role === 'admin' ? [...operator, ...administrator] : operator
  }

  return [...(org.isClient ? client : []), ...(org.isContractor ? contractor : [])]
}
