import { sql } from 'drizzle-orm'
import { index, jsonb, pgSchema, text, timestamp, uuid } from 'drizzle-orm/pg-core'

/**
 * Схема `admin` — журнал изменений, и пока больше ничего.
 *
 * Своих данных у админки почти нет: она смотрит чужие и меняет их вызовом
 * команд модулей-владельцев (§4). Журнал — единственное исключение: он
 * принадлежит ей, потому что не принадлежит никому другому.
 */
export const admin = pgSchema('admin')

/**
 * Кто, что и когда изменил — со старым значением и новым.
 *
 * НА ЭТОЙ ТАБЛИЦЕ ДЕРЖИТСЯ ДОВЕРИЕ К ПЛОЩАДКЕ. Мы берём деньги за то, что
 * стоим между сторонами сделки, и однажды придётся ответить на вопрос
 * «почему у меня изменилась ставка» или «кто снял мою карточку». Ответ
 * «система так решила» стоит клиента.
 *
 * Отсюда три свойства, каждое из которых важнее удобства:
 *
 * 1. **Запись идёт в той же транзакции, что и само изменение.** Иначе журнал
 *    врёт при откате: изменение не состоялось, а запись о нём осталась.
 *    Поэтому `logChange` принимает транзакцию вызывающего, как и `publish`.
 *
 * 2. **Старое значение и новое, а не факт изменения.** «Ставка изменена»
 *    не отвечает ни на один вопрос. «Было 10 %, стало 12 %» отвечает.
 *
 * 3. **Имя и роль автора — снимком, а не ссылкой.** Человека переименуют,
 *    уволят, отзовут ему доступ, а журнал обязан читаться через год.
 *    Ссылка на `platform.users` здесь дала бы «сотрудник не найден» там,
 *    где нужен ответ.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ ДОЛЖНО ПОЯВИТЬСЯ: команд изменения и удаления записи.
 * Журнал, который можно поправить, не журнал. Их нет не в интерфейсе,
 * а в самом модуле — вызвать нечего.
 */
export const auditLog = admin.table(
  'audit_log',
  {
    id: uuid('id').primaryKey(),

    /**
     * Ссылки на `platform.users` нет намеренно: между схемами их не бывает
     * (§4.3), да и запись обязана пережить удаление учётной записи.
     */
    actorId: uuid('actor_id').notNull(),
    actorName: text('actor_name').notNull(),
    actorRole: text('actor_role').notNull(),

    /** Что сделал: `contractor.verified`, `org.blocked`, `rate.changed`. */
    action: text('action').notNull(),
    /** Над чем: `catalog.contractor`, `platform.org`. Модуль в имени — нарочно. */
    entity: text('entity').notNull(),
    entityId: uuid('entity_id').notNull(),
    /** Как человек называл это в момент действия: «Кофейня на Тверской». */
    entityLabel: text('entity_label'),

    /** Было и стало. `null` в `before` — значит создано, в `after` — удалено. */
    before: jsonb('before'),
    after: jsonb('after'),

    /**
     * Зачем. Для блокировки компании обязательна — так требует 03-2,
     * и причина нужна не нам, а тому, кого заблокировали.
     */
    reason: text('reason'),

    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // Журнал читают с конца: «что вообще происходило», а потом сужают
    index('audit_log_recent_idx').on(sql`${t.createdAt} desc`),
    index('audit_log_entity_idx').on(t.entity, t.entityId, sql`${t.createdAt} desc`),
    index('audit_log_actor_idx').on(t.actorId, sql`${t.createdAt} desc`),
  ],
)
