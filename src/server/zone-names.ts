import { findZone } from '@/modules/catalog'

/**
 * Коды зон — во внутрь, названия — наружу.
 *
 * В базе округ хранится кодом (`msk-cao`): один источник, никаких «МСК-ЦАО»
 * и «центр» вперемешку. Но код — системный термин, а §7.1 запрещает им
 * протекать в интерфейс: человек, выбирающий уборку, видит «Центральный»,
 * а не `msk-cao`. Один раз это уже протекло на карточку услуги, поэтому
 * перевод живёт отдельной функцией и проверяется тестом.
 *
 * Незнакомый код показывается как есть: витрина не должна прятать зону
 * из-за того, что словарь отстал от базы. Пустое место читалось бы как
 * «никуда не выезжают», а это неправда.
 */
export function zoneNames(codes: readonly string[]): string[] {
  return codes.map((code) => findZone(code)?.name ?? code)
}
